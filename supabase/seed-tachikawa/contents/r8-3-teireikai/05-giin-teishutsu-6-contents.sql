- **燃料の優先供給**：救助や復旧、住民の生活に欠かせないガソリンや軽油を、優先してすばやく届ける仕組みをつくること
- **二次災害への備え**：地震のあとの土砂災害などを防ぐため、地面や斜面の動きの監視を強め、住民にわかりやすく早く知らせること

