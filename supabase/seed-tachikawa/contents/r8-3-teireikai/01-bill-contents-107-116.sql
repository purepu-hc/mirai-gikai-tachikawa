保育所などで子どもへの虐待が起きたときに、**市の対応をチェックする専門家の会議**を新しくつくるための条例です。

## なにが変わる？

- 「**立川市子どもの福祉審議会**」という会議が新しくできます
- 保育所などで虐待があり、市が対応（措置）をとったとき、その**内容と、その後の子どもの様子**について報告を受けて、調べたり話し合ったりします
- このほか、市長が必要と考えたことも話し合います

## どんな人がメンバー？

5人以内で、市長が次の分野から1人ずつ選びます。

- 弁護士
- 医師
- 子どもの福祉にくわしい学者などの専門家
- 子どもの福祉の行政の経験がある人
- 子どもの福祉の施設で働いている人

任期は2年です。メンバーは会議で知った秘密を、辞めたあとも外に漏らしてはいけません。

## だれに関係ある？

保育所などに子どもを預けている家庭や、保育・子どもの福祉の施設で働く人に関係があります。

